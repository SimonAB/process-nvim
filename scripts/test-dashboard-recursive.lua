-- Verify recursive dashboard discovery, modification ordering and file actions.
vim.opt.rtp:prepend(vim.fn.getcwd())
local content = require("plugins.mini-nvim.dashboard-content")
local root = vim.fn.tempname()
vim.fn.mkdir(root .. "/nested/deeper", "p")
vim.fn.mkdir(root .. "/ignored", "p")
vim.fn.writefile({"ignored/"}, root .. "/.ignore")
vim.fn.writefile({"old"}, root .. "/top.jl")
vim.fn.writefile({"new"}, root .. "/nested/deeper/new file.jl")
vim.fn.writefile({"hidden"}, root .. "/nested/.hidden")
vim.fn.writefile({"ignored"}, root .. "/ignored/skip.jl")
local fd = assert(vim.uv.fs_open(root .. "/nested/binary", "w", 384))
vim.uv.fs_write(fd, "binary\0data", 0)
vim.uv.fs_close(fd)
vim.uv.fs_utime(root .. "/top.jl", 10, 10)
vim.uv.fs_utime(root .. "/nested/deeper/new file.jl", 20, 20)
vim.cmd.cd(root)
local items = content.create_cwd_files()
assert(#items == 2, "Only visible, unignored text files should be shown")
assert(items[1].name == "a.  nested/deeper/new file.jl", "Nested newest file with relative path")
assert(items[2].name == "b.  top.jl", "Top-level files retained")
items[1].action()
assert(vim.uv.fs_realpath(vim.api.nvim_buf_get_name(0)) == vim.uv.fs_realpath(root .. "/nested/deeper/new file.jl"))
vim.fn.delete(root, "rf")
print("Recursive dashboard discovery and file action passed")
vim.cmd("qa!")
