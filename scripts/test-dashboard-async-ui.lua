-- Verify background results update only the matching dashboard and its shortcuts.
vim.opt.rtp:prepend(vim.fn.getcwd())
vim.opt.rtp:append(vim.fn.stdpath("data") .. "/site/pack/core/opt/mini.nvim")
local root = vim.fn.tempname()
vim.fn.mkdir(root .. "/first", "p")
vim.fn.mkdir(root .. "/second", "p")
vim.fn.writefile({"first"}, root .. "/first/first.jl")
vim.fn.writefile({"second"}, root .. "/second/second.jl")
vim.fn.writefile({"older"}, root .. "/second/older.jl")
vim.uv.fs_utime(root .. "/second/older.jl", 10, 10)
vim.cmd.cd(root .. "/first")
local dashboard = require("plugins.mini-nvim.dashboard")
local files = require("core.dashboard-files")
dashboard.setup()
dashboard.setup_keymaps()
dashboard.setup_autocommands()
MiniStarter.open()
local buf = vim.api.nvim_get_current_buf()
-- Change directory before the first scan returns.
vim.cmd.cd(root .. "/second")
local function text()
	return table.concat(vim.api.nvim_buf_get_lines(buf, 0, -1, false), "\n")
end
assert(vim.wait(3000, function() return text():find("a.  second.jl", 1, true) end))
assert(not text():find("a.  first.jl", 1, true), "Old cwd results must not overwrite new cwd")
assert(vim.fn.maparg("b", "n", false, true).desc == "Open cwd file b")
vim.fn.delete(root .. "/second/older.jl")
files.invalidate(root .. "/second/older.jl")
dashboard.refresh()
assert(vim.wait(3000, function() return not text():find("older.jl", 1, true) end))
assert(vim.fn.maparg("b", "n", false, true).callback == nil, "Remove stale shortcut")
vim.fn.maparg("a", "n", false, true).callback()
assert(vim.api.nvim_buf_get_name(0):match("/second/second.jl$"), "Rebound shortcut opens latest result")
-- Save a new file: the real autocmd must invalidate the directory cache.
vim.cmd.edit(root .. "/second/latest.jl")
vim.api.nvim_buf_set_lines(0, 0, -1, false, {"latest"})
vim.cmd.write()
vim.fn.maparg("<leader>H", "n", false, true).callback()
buf = vim.api.nvim_get_current_buf()
assert(vim.wait(3000, function() return text():find("a.  latest.jl", 1, true) end))
vim.fn.delete(root, "rf")
print("Dashboard cwd isolation, refreshed shortcuts and save invalidation passed")
vim.cmd("qa!")
